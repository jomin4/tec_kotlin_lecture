// 섹션 3 - 강의 1: 코틀린에서 함수를 다루는 방법
// 실행:  .\run.ps1 section03\Lesson01.kt

fun main() {
    // ============================================================
    // ① 기본 함수 호출
    // ============================================================
    println("add(2, 3) = ${add(2, 3)}")
    println("addExpr(2, 3) = ${addExpr(2, 3)}")
    println("max(7, 4) = ${max(7, 4)}")

    // ============================================================
    // ② default 파라미터 — 인자를 생략하면 기본값 사용
    // ============================================================
    greet("철수")                 // msg="안녕하세요", times=1
    greet("영희", "반가워")        // times=1
    greet("민수", "하이", 3)       // 전부 지정

    // ============================================================
    // ③ named 파라미터 — 이름을 붙여 호출 (순서 무관, 중간 건너뛰기)
    // ============================================================
    greet(name = "지수", times = 2)          // msg는 기본값, times만 지정
    greet(times = 3, name = "현우")          // 순서를 바꿔도 됨

    // ============================================================
    // ④ 실전: 함수를 표현식으로 짧게
    // ============================================================
    println("원의 넓이(반지름 5) = ${circleArea(5.0)}")
}

// ① 블록 몸통 함수 (전통적인 형태)
fun add(a: Int, b: Int): Int {
    return a + b
}

// ② 표현식 함수 — { return } 을 = 로 압축
fun addExpr(a: Int, b: Int): Int = a + b

// 반환 타입도 추론되면 생략 가능
fun max(a: Int, b: Int) = if (a > b) a else b

// ③ default 파라미터 — msg와 times에 기본값
fun greet(name: String, msg: String = "안녕하세요", times: Int = 1) {
    for (i in 1..times) {
        println("$name 님, $msg (${i}번째)")
    }
}

// ④ 표현식 함수 + 상수 활용
fun circleArea(radius: Double) = 3.14 * radius * radius
