// 섹션 3 - 강의 2: 코틀린에서 확장 함수 (Extension Functions)
// 실행:  .\run.ps1 section03\Lesson02.kt

fun main() {
    // ============================================================
    // ① String에 내 함수를 붙여서 원래 메서드처럼 호출
    // ============================================================
    val word = "코틀린"
    println("마지막 글자: ${word.lastChar()}")      // '린'
    println("첫 글자: ${word.firstChar()}")         // '코'

    // ============================================================
    // ② Int에도 확장 함수 — 짝수 판별
    // ============================================================
    println("4는 짝수? ${4.isEven()}")
    println("7는 짝수? ${7.isEven()}")

    // ============================================================
    // ③ 파라미터가 있는 확장 함수
    // ============================================================
    println("'*'로 감싸기: ${"hello".wrap("*")}")   // *hello*

    // ============================================================
    // ④ 확장 함수도 default 파라미터 가능
    // ============================================================
    println("반복: ${"야".repeatText()}")           // 야야야 (기본 3회)
    println("반복: ${"코".repeatText(5)}")           // 코코코코코

    // ============================================================
    // ⑤ 멤버 함수가 있으면 멤버가 이긴다 (확장은 무시됨)
    //    - 실무 주의점: 같은 이름이면 원래 클래스 함수가 우선
    // ============================================================
    println("length는 멤버 함수 우선: ${"abcde".length}")
}

// ① 수신 객체 타입 = String. 함수 안 this = 나를 호출한 그 String
fun String.lastChar(): Char = this[this.length - 1]
fun String.firstChar(): Char = this[0]

// ② Int 확장 함수
fun Int.isEven(): Boolean = this % 2 == 0

// ③ 파라미터 있는 확장 함수 (this를 mark로 감싼다)
fun String.wrap(mark: String): String = "$mark$this$mark"

// ④ default 파라미터 있는 확장 함수
fun String.repeatText(times: Int = 3): String {
    var result = ""
    for (i in 1..times) result += this
    return result
}
