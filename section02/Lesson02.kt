// 섹션 2 - 강의 2: 코틀린에서 when (자바 switch의 강화판)
// 실행:  .\run.ps1 section02\Lesson02.kt

fun main() {
    // ============================================================
    // ① 기본 when — 여러 값은 콤마로, break 불필요, else = default
    // ============================================================
    val day = 6
    val type = when (day) {
        1, 2, 3, 4, 5 -> "주중"     // 콤마로 여러 값
        6, 7 -> "주말"
        else -> "잘못된 요일"
    }
    println("day=$day → $type")

    // ============================================================
    // ② when도 '표현식' — 값을 반환해 변수에 담긴다 (위 type이 이미 그 예)
    //    분기 조건에 '범위(in)' 사용 — switch로는 불가능했던 것
    // ============================================================
    val n = 57
    val digits = when (n) {
        in 0..9 -> "한 자리"
        in 10..99 -> "두 자리"
        in 100..999 -> "세 자리"
        else -> "네 자리 이상"
    }
    println("$n 은 $digits 수")

    // ============================================================
    // ③ 타입 분기 (is) + 스마트 캐스트 — 이것도 switch로는 불가
    // ============================================================
    describe("코틀린")
    describe(100)
    describe(3.14)

    // ============================================================
    // ④ 인자 없는 when — 각 분기에 boolean 조건 직접 (if/else if 대체)
    // ============================================================
    val score = 85
    val grade = when {
        score >= 90 -> "A"
        score >= 80 -> "B"
        score >= 70 -> "C"
        else -> "F"
    }
    println("점수 $score → 학점 $grade")

    // ============================================================
    // ⑤ 문(statement)으로도 쓸 수 있다 (값 안 받고 실행만)
    // ============================================================
    when (day) {
        6, 7 -> println("오늘은 쉬는 날!")
        else -> println("오늘은 일하는 날")
    }
}

// when + is 로 타입에 따라 다르게 처리
fun describe(value: Any) {
    val msg = when (value) {
        is String -> "문자열, 길이 ${value.length}"   // 스마트 캐스트
        is Int -> "정수, 제곱 ${value * value}"
        else -> "기타 타입: $value"
    }
    println(msg)
}
