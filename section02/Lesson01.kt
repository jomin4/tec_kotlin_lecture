// 섹션 2 - 강의 1: 코틀린에서 if문 (표현식)
// 실행:  .\run.ps1 section02\Lesson01.kt

fun main() {
    val a = 7
    val b = 3

    // ============================================================
    // ① 기본 if — 자바와 똑같이 '문'으로도 쓸 수 있다
    // ============================================================
    if (a > b) {
        println("a가 b보다 크다")
    } else {
        println("a가 b보다 크지 않다")
    }

    // ============================================================
    // ② if가 '표현식' — 값을 반환해서 변수에 담는다 (삼항연산자 대체)
    // ============================================================
    val max = if (a > b) a else b
    println("max = $max")

    // 블록을 쓰면 '마지막 줄'이 그 값
    val bigger = if (a > b) {
        println("(a를 선택)")
        a
    } else {
        println("(b를 선택)")
        b
    }
    println("bigger = $bigger")

    // ============================================================
    // ③ else if 로 여러 갈래 — 이것도 값을 반환할 수 있다
    // ============================================================
    val score = 85
    val grade = if (score >= 90) {
        "A"
    } else if (score >= 80) {
        "B"
    } else if (score >= 70) {
        "C"
    } else {
        "F"
    }
    println("점수 $score → 학점 $grade")

    // ============================================================
    // ④ 함수 반환에도 바로 활용 (if 자체가 값이니까)
    // ============================================================
    println("절댓값(-5) = ${abs(-5)}")
    println("절댓값(5)  = ${abs(5)}")

    // ⑤ 범위와 결합: in 으로 '어느 구간인지'
    val temp = 26
    val feel = if (temp in 28..100) "덥다"
               else if (temp in 18..27) "적당하다"
               else "춥다"
    println("기온 $temp → $feel")
}

// if를 그대로 return — 표현식이라 가능
fun abs(x: Int): Int {
    return if (x < 0) -x else x
}
