// 섹션 2 - 강의 3: 코틀린에서 반복문 (for / while)
// 실행:  .\run.ps1 section02\Lesson03.kt

fun main() {
    // ============================================================
    // ① for + 범위 — C 스타일 for는 없다. 범위(range)를 순회
    // ============================================================
    print("1..5 (끝 포함):   ")
    for (i in 1..5) print("$i ")
    println()

    print("1 until 5 (끝 제외): ")
    for (i in 1 until 5) print("$i ")   // 5 미포함
    println()

    print("5 downTo 1 (역순):  ")
    for (i in 5 downTo 1) print("$i ")
    println()

    print("1..10 step 2 (2씩):  ")
    for (i in 1..10 step 2) print("$i ")
    println()

    // ============================================================
    // ② for-each — 컬렉션 순회 (자바의 콜론 대신 in)
    // ============================================================
    val names = listOf("김코틀린", "이자바", "박스칼라")
    print("이름들: ")
    for (name in names) print("$name ")
    println()

    // 인덱스가 필요하면 withIndex()
    for ((idx, name) in names.withIndex()) {
        println("  [$idx] $name")
    }

    // ============================================================
    // ③ while — 자바와 완전히 동일
    // ============================================================
    var i = 1
    var sum = 0
    while (i <= 100) {
        sum += i
        i++
    }
    println("1부터 100까지 합 = $sum")

    // ============================================================
    // ④ do-while — 조건이 거짓이어도 '최소 한 번'은 실행
    // ============================================================
    var count = 5
    do {
        println("발사까지 $count")
        count--
    } while (count > 0)
    println("발사!")

    // ============================================================
    // ⑤ 실전 예: 구구단 3단 (범위 중첩)
    // ============================================================
    println("=== 3단 ===")
    for (n in 1..9) {
        println("3 x $n = ${3 * n}")
    }
}
