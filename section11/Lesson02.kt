// 고급편 섹션3(복잡한 함수형) - 강의2: 시퀀스 (Sequence, lazy 평가)
// 실행:  .\run.ps1 section11\Lesson02.kt

fun main() {
    val nums = listOf(1, 2, 3, 4)

    // ============================================================
    // ① 컬렉션 (eager) — filter를 "전부" 하고, 그다음 map을 "전부"
    //    로그를 보면 filter가 4번 다 돈 뒤 map이 돈다 (단계별 = 가로 처리)
    // ============================================================
    println("=== 컬렉션 (eager) ===")
    val eager = nums
        .filter { println("  filter($it)"); it % 2 == 0 }
        .map { println("  map($it)"); it * 10 }
    println("결과 = $eager")

    // ============================================================
    // ② 시퀀스 (lazy) — 원소 하나가 filter→map을 통과, 그다음 원소
    //    로그가 filter(1), filter(2), map(2)... 처럼 섞인다 (원소별 = 세로 처리)
    // ============================================================
    println("=== 시퀀스 (lazy) ===")
    val lazy = nums.asSequence()
        .filter { println("  filter($it)"); it % 2 == 0 }   // 중간 연산 (아직 실행 X)
        .map { println("  map($it)"); it * 10 }             // 중간 연산 (아직 실행 X)
        .toList()                                            // 최종 연산 → 여기서 실행
    println("결과 = $lazy")

    // ============================================================
    // ③ 최종 연산이 없으면 시퀀스는 아무것도 안 한다
    // ============================================================
    println("=== 최종 연산 없음 ===")
    nums.asSequence().filter { println("  이 줄은 안 불림!"); it > 0 }   // 로그 안 뜸
    println("(중간 연산만 걸면 계산 자체가 일어나지 않음)")

    // ============================================================
    // ④ 조기 종료 — first/take는 필요한 만큼만 계산하고 멈춘다
    //    1~100인데 map이 몇 번만 도는지 로그로 확인
    // ============================================================
    println("=== 조기 종료 ===")
    val firstBig = (1..100).asSequence()
        .map { println("  map($it)"); it * it }
        .first { it > 10 }         // 제곱이 10 넘는 첫 값
    println("결과 = $firstBig")     // 16 (4의 제곱). map은 4번만 돎, 100번 아님
}
